import { MetadataRoute } from 'next'

const disallow = ['/admin/', '/api/admin/']

// AI crawlers are named explicitly so the welcome is unambiguous. Answer engines (ChatGPT search,
// Claude, Perplexity, Gemini, Copilot) can only cite pages their bots are allowed to fetch, and
// training crawlers put Growmax into the models' own knowledge of B2B commerce vendors.
// A named group does not inherit the '*' group, so it repeats the same disallow list.
const aiCrawlers = [
  // OpenAI: search index, user-triggered browsing, training
  'OAI-SearchBot', 'ChatGPT-User', 'GPTBot',
  // Anthropic: search index, user-triggered fetches, training
  'Claude-SearchBot', 'Claude-User', 'ClaudeBot',
  // Perplexity: index and user-triggered fetches
  'PerplexityBot', 'Perplexity-User',
  // Google Gemini / AI Overviews grounding, Apple Intelligence, Amazon, Meta, Mistral, DuckDuckGo
  'Google-Extended', 'Applebot-Extended', 'Amazonbot', 'meta-externalagent', 'MistralAI-User', 'DuckAssistBot',
  // Common Crawl feeds many open models
  'CCBot',
]

export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      { userAgent: '*', allow: '/', disallow },
      { userAgent: aiCrawlers, allow: '/', disallow },
    ],
    // The docs at /docs keep their own sitemap (generated by the ARC docs site).
    sitemap: ['https://www.growmax.io/sitemap.xml', 'https://www.growmax.io/docs/sitemap.xml'],
  }
}
